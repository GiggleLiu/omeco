def fig4():
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.4))
    meta = {"reg3_250": (250, 30.0, None), "sycamore_m20": (561, 47.0, (141, 40))}
    for ax, inst in zip(axes, ["reg3_250", "sycamore_m20"]):
        ks, spec, emp = [], [], []
        with open(ROOT / f".worktrees/attempt-031/data/{inst}_profile.csv") as f:
            for row in csv.DictReader(f):
                k = int(row["k"])
                if k < 1:
                    continue
                ks.append(k)
                spec.append(float(row["b_spec"]))
                emp.append(float(row["b_emp_windowmin"]))
        n, bis, cert = meta[inst]
        ax.plot(ks, emp, color=BLUE, lw=2, label="empirical profile $b(k)$ (upper est.)")
        ax.plot(ks, spec, color=RED, lw=2, ls="--", label=r"spectral bound $\lambda_2 k(n{-}k)/n$")
        ax.axhline(bis, color=BLACK, lw=2, ls=":")
        ax.text(0.02 * n, bis + 0.8, "bisection width", fontsize=8)
        if cert:
            ax.plot([cert[0]], [cert[1]], marker="*", ms=14, color=ORANGE, zorder=6,
                    label="certified cut: $|S|{=}141$, $|\\partial S|{=}40$")
        ax.set_xlabel("subset size $k$  [tensors]")
        ax.set_ylabel(r"boundary $|\partial S|$  [log$_2$ size]" if inst == "reg3_250" else "")
        ax.set_title(inst, fontsize=11)
        ax.legend(loc="upper right" if inst == "reg3_250" else "lower center",
                  frameon=False, fontsize=8)
    save(fig, "fig4_isoperimetric_profiles")


