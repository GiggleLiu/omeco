# ---------------------------------------------------------------- F1 sweep (if data ready)
def fig1():
    path = ART / "data/sweep_sctarget.jsonl"
    if not path.exists() or path.stat().st_size == 0:
        print("F1: sweep data not ready, skipping")
        return
    import collections
    runs = collections.defaultdict(list)
    for line in open(path):
        d = json.loads(line)
        runs[(d["instance"], d["sc_target"])].append(d["result"]["tc"])
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.4))
    order = {"reg3_250": ["10", "15", "20", "25", "30", "34", "40", "50", "inf"],
             "sycamore_m20": ["20", "30", "40", "45", "50", "53", "60", "70", "inf"]}
    frontier = {"reg3_250": 39.95, "sycamore_m20": 61.544}
    natural = {"reg3_250": 34, "sycamore_m20": 53}
    for ax, inst in zip(axes, order):
        xs, meds, los, his = [], [], [], []
        for i, v in enumerate(order[inst]):
            vals = sorted(runs.get((inst, v), []))
            if not vals:
                continue
            xs.append(i)
            meds.append(vals[len(vals) // 2])
            los.append(vals[0])
            his.append(vals[-1])
        ax.errorbar(xs, meds,
                    yerr=[[m - l for m, l in zip(meds, los)],
                          [h - m for m, h in zip(meds, his)]],
                    fmt="o", color=BLUE, capsize=3, lw=2, ms=6,
                    label="median of 3 (range)")
        ax.axhline(frontier[inst], color=BLACK, lw=2, ls="--")
        ax.text(0.1, frontier[inst], " frontier", va="bottom", fontsize=8)
        nat_idx = order[inst].index(str(natural[inst]))
        ax.axvline(nat_idx, color=RED, lw=1.5, ls=":")
        ax.text(nat_idx, ax.get_ylim()[1], " natural sc", fontsize=8, color=RED,
                va="top")
        ax.set_xticks(range(len(order[inst])))
        ax.set_xticklabels([v if v != "inf" else r"$\infty$" for v in order[inst]])
        ax.set_xlabel(r"sc$_{\mathrm{target}}$  [log$_2$ memory]")
        ax.set_ylabel(r"best tc at 90 s  [log$_2$ flops]" if inst == "reg3_250" else "")
        ax.set_title(inst, fontsize=11)
        ax.legend(frameon=False, fontsize=8)
    save(fig, "fig1_sctarget_sweep")


